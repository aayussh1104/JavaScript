// Array push pop

// Array shift unshift
let fruits = ["Apples","Grapes","Mangoes","Watermelons"];

// push --> adds in the last
console.log(fruits);
fruits.push("Banana");
console.log(fruits);

// pop --> removes last element from the array
console.log(fruits);
fruits.pop();
console.log(fruits);

// unshift --> adds elements in the starting
fruits.unshift("Litchis");
console.log(fruits);

//shift --> removes first element from the starting
fruits.shift();
console.log(fruits);