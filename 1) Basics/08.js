// typeof operators
  // Data types(primitive data types)
  // number = 6,4,5.7
  // string = "Aayush"
  // booleans
  // undefined
  // null
  // BigInt
  // Symbol

let age= 22;
let name="Aayush";

console.log(typeof age);
console.log(typeof name);

// Convert number into string = add an empty string to that number or variable
age = age +"";
console.log(typeof age);

// Convert string into number  = add + infront of the string
let myString = "34";
console.log(typeof myString);

let newString= +"34";
console.log(typeof newString);

// Direct changing
let age1 = 2;
age1 = String(age1);
console.log(typeof age1);

let string1 = "1125";
string1 = Number(string1);
console.log(typeof string1);


